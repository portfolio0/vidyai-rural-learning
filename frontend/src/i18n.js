// Retrieve stored language or fallback to 'en'
const storedLang =
  typeof window !== "undefined"
    ? localStorage.getItem("vidyai-lang") || "en"
    : "en";

i18n.use(initReactI18next).init({
  resources,
  lng: storedLang,
  fallbackLng: "en",
  interpolation: {
    escapeValue: false,
  },
});

export const setAppLanguage = (lang) => {
  if (["en", "mr", "hi"].includes(lang)) {
    i18n.changeLanguage(lang);
    if (typeof window !== "undefined") {
      localStorage.setItem("vidyai-lang", lang);
    }
  }
};

export default i18n;
